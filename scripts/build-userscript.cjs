const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const version = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8')).version;
const header = `// ==UserScript==
// @name         Fix Gemini Parser
// @namespace    http://tampermonkey.net/
// @version      ${version}
// @description  Gemini의 스트리밍 마크다운과 수식을 원본 DOM을 유지하며 렌더링합니다.
// @author       kangjoseph90
// @match        https://gemini.google.com/*
// @grant        GM_getResourceText
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_registerMenuCommand
// @require      https://cdn.jsdelivr.net/npm/katex@0.16.9/dist/katex.min.js
// @require      https://cdn.jsdelivr.net/npm/markdown-it@14.1.0/dist/markdown-it.min.js
// @resource     KATEX_CSS https://cdn.jsdelivr.net/npm/katex@0.16.9/dist/katex.min.css
// ==/UserScript==

// Generated by scripts/build-userscript.cjs. Edit parser-engine.js or userscript-bootstrap.js.
`;
const output = header + ['parser-engine.js', 'userscript-bootstrap.js'].map(name => fs.readFileSync(path.join(root, name), 'utf8')).join('\n');
const destination = path.join(root, 'user-script.js');
if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== output) {
        console.error('user-script.js is out of date. Run npm run build:userscript.'); process.exitCode = 1;
    }
} else fs.writeFileSync(destination, output);
